test("单 Controller 串行化防重入与非法 Slash 命令拦截", async () => {
    const { workspace, cleanup } = await setupE2eWorkspace();
    try {
        const catalogModels = [createDescriptor("model-alpha", "Model Alpha")];
        const initialAdapter = new SensitiveFakeAdapter("model-alpha");

        const root = await createCompositionRoot({
            cwd: workspace,
            env: { LAZYGOAL_HOME: join(workspace, "lazygoal-home") },
            adapter: initialAdapter,
            modelCatalog: new FakeCatalog(catalogModels),
            adapterFactory: (sel) => new SensitiveFakeAdapter(sel.modelId),
            profile: {
                id: "default",
                systemPrompt: "System prompt",
                instructions: [],
                toolIds: [],
            },
            toolPolicy: createDefaultToolPolicy(),
        });

        // 1. 非法 Slash 命令拦截
        const registry = createSlashCommandRegistry<ModelCommandEffect>();
        registry.register(modelCommandDefinition);

        const invalidCommand = "/nonexistent-command foo bar";
        const dispatchResult = await registry.dispatch(invalidCommand);
        assert.equal(dispatchResult.kind, "rejected");
        assert.match(dispatchResult.message, /Unknown slash command/i);

        // 2. 正常创建 Goal
        await root.controller.dispatch({
            kind: "create",
            intent: "Regular goal creation",
        });
        assert.equal(root.controller.getSnapshot().screen, "session");

        // 3. 验证并发重入防护：正在执行命令时派发第二个命令被快速拒绝
        let slowAdapterResolve: (() => void) | undefined;
        const slowAdapterPromise = new Promise<void>((resolve) => {
            slowAdapterResolve = resolve;
        });

        class SlowAdapter implements LLMAdapter {
            readonly provider = "openai";
            readonly structuredOutputMode = "strict" as const;
            async generate(): Promise<LLMResponse> {
                await slowAdapterPromise;
                return {
                    content: JSON.stringify({
                        result: {
                            kind: "question",
                            question: "Next question",
                            memoryPatch: null,
                        },
                    }),
                };
            }
        }

        const slowAdapter = new SlowAdapter();
        const slowRoot = await createCompositionRoot({
            cwd: workspace,
            env: { LAZYGOAL_HOME: join(workspace, "lazygoal-home") },
            adapter: slowAdapter,
            modelCatalog: new FakeCatalog(catalogModels),
            profile: {
                id: "default",
                systemPrompt: "System prompt",
                instructions: [],
                toolIds: [],
            },
            toolPolicy: createDefaultToolPolicy(),
        });

        // 启动一个耗时的 dispatch
        const p1 = slowRoot.controller.dispatch({
            kind: "create",
            intent: "Long running task",
        });

        // 立即尝试第二次 dispatch
        await assert.rejects(
            slowRoot.controller.dispatch({
                kind: "create",
                intent: "Conflicting task",
            }),
            /Another UI command is already in progress/i,
        );

        // 释放第一次 dispatch
        slowAdapterResolve?.();
        await p1;
    } finally {
        await cleanup();
    }
});
