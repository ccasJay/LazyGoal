        await root1.controller.dispatch({
            kind: "selectModel",
            model: catalogModels[1]!,
        });

        const goalId = root1.controller.getSnapshot().screen === "session"
            ? (root1.controller.getSnapshot() as any).goal.id
            : "";
        assert.ok(goalId.length > 0);

