function createDescriptor(
    id: string,
    displayName: string,
    provider: LlmProvider = "openai",
    selectable = true,
): LlmModelDescriptor {
    return {
        id,
        displayName,
        provider,
        selectable,
        availabilitySource: "live",
        metadataSource: "catalog",
        contextWindowTokens: 128_000,
        maxOutputTokens: 4096,
    };
}

async function setupE2eWorkspace(): Promise<{ workspace: string; cleanup: () => Promise<void> }> {
    const workspace = await mkdtemp(join(tmpdir(), "lazygoal-e2e-canary-"));
    return {
        workspace,
        cleanup: async () => {
            await rm(workspace, { recursive: true, force: true });
        },
    };
}

/** 递归扫描目录下所有文件的文本内容，用于断言无任何 canary 敏感字符串泄漏。 */
async function scanDirectoryForSecret(dir: string, secret: string): Promise<string[]> {
    const leakPaths: string[] = [];
    async function walk(currentDir: string): Promise<void> {
        let entries;
        try {
            entries = await readdir(currentDir, { withFileTypes: true });
        } catch {
            return;
        }
        for (const entry of entries) {
            const full = join(currentDir, entry.name);
            if (entry.isDirectory()) {
                await walk(full);
            } else if (entry.isFile()) {
                const text = await readFile(full, "utf8");
                if (text.includes(secret)) {
                    leakPaths.push(full);
                }
            }
        }
    }
    await walk(dir);
    return leakPaths;
}

test("端到端组合流：// 转义入会话、/model 命令被拦截不入会话、模型切换后后续推进使用新模型", async () => {
    const { workspace, cleanup } = await setupE2eWorkspace();
    try {
        const adapterMap = new Map<string, SensitiveFakeAdapter>();
        const catalogModels = [
            createDescriptor("model-alpha", "Model Alpha (Default)"),
            createDescriptor("model-beta", "Model Beta (Upgraded)"),
        ];

        const initialAdapter = new SensitiveFakeAdapter("model-alpha");
        adapterMap.set("model-alpha", initialAdapter);

        // 真实实例化 Composition Root，不 mock 持久化，所有文件写入 workspace 对应的 Home。
        const root = await createCompositionRoot({
            cwd: workspace,
            env: { LAZYGOAL_HOME: join(workspace, "lazygoal-home") },
            adapter: initialAdapter,
            modelCatalog: new FakeCatalog(catalogModels),
            adapterFactory: (sel) => {
                let adp = adapterMap.get(sel.modelId);
                if (!adp) {
                    adp = new SensitiveFakeAdapter(sel.modelId);
                    adapterMap.set(sel.modelId, adp);
                }
                return adp;
            },
            profile: {
                id: "default",
                systemPrompt: "You are an AI assistant.",
                instructions: [],
                toolIds: [],
            },
            toolPolicy: createDefaultToolPolicy(),
        });

        const capturedViewModels: UiViewModel[] = [];
        root.controller.subscribe(() => {
            capturedViewModels.push(root.controller.getSnapshot());
        });

        // 1. 初始化 SlashCommandRegistry，模拟文本输入框组件的行为
        const registry = createSlashCommandRegistry<ModelCommandEffect>();
        registry.register(modelCommandDefinition);

        // 2. 测试 // 转义输入提交
        const escapedInput = "//Create a service with /model in name";
        const dispatchResult1 = await registry.dispatch(escapedInput);
        assert.equal(dispatchResult1.kind, "escaped_text");
        assert.equal(dispatchResult1.content, "/Create a service with /model in name");

        // 派发转义后的文本作为 intent 创建 Goal
        await root.controller.dispatch({
            kind: "create",
            intent: dispatchResult1.content,
        });

        const sessionView1 = root.controller.getSnapshot();
        assert.equal(sessionView1.screen, "session");
        assert.equal(sessionView1.waitingFor, "ask_user");

        // 验证 Goal messages 与状态包含转义后的普通文本
        assert.ok(sessionView1.goal.state.messages.length > 0);
        assert.equal(
            sessionView1.goal.state.messages[0]?.content,
            "/Create a service with /model in name",
        );
        // 第一轮执行使用的是 model-alpha
        assert.equal(initialAdapter.calls.length, 1);

        // 3. 在会话等待点模拟输入 /model
        const slashInput = "/model";
        const dispatchResult2 = await registry.dispatch(slashInput);
        assert.equal(dispatchResult2.kind, "executed");
        assert.equal(dispatchResult2.effect.kind, "open_model_selector");

        // 派发 openModelSelector 命令
        await root.controller.dispatch({ kind: "openModelSelector" });

        // 验证进入 model_select 屏幕
        const selectView = root.controller.getSnapshot();
        assert.equal(selectView.screen, "model_select");

        // 关键断言：/model 命令文本绝不能进入 Goal 的任何 messages 中！
        for (const msg of selectView.goal?.state.messages ?? []) {
            assert.notEqual(msg.content, "/model");
        }

        // 4. 选择新模型 model-beta
        await root.controller.dispatch({
            kind: "selectModel",
            model: catalogModels[1]!,
        });

        // 切换后回到 session 屏幕，并展示切换 notice
        const sessionView2 = root.controller.getSnapshot();
        assert.equal(sessionView2.screen, "session");
        assert.equal(sessionView2.notice?.kind, "info");
        assert.match(sessionView2.notice?.message ?? "", /Model switched to Model Beta \(Upgraded\)/);
        assert.equal(sessionView2.goal.state.modelSelection?.modelId, "model-beta");
        assert.equal(root.modelBinding.current().selection.modelId, "model-beta");

        // 5. 提交后续回答，推进执行
        assert.ok(sessionView2.askUser !== undefined);
        await root.controller.dispatch({
            kind: "answerAskUser",
            requestId: sessionView2.askUser.requestId,
            answers: [
                {
                    questionId: sessionView2.askUser.questions[0]!.id,
                    optionIds: [sessionView2.askUser.questions[0]!.options[0]!.id],
                },
            ],
        });

        // 切换后的新请求必须路由到 model-beta 对应的 Adapter
        const betaAdapter = adapterMap.get("model-beta");
        assert.ok(betaAdapter !== undefined);
        assert.ok(betaAdapter.calls.length >= 1);

        // 验证 notice 在下一次交互推进后被自动清除
        const sessionView3 = root.controller.getSnapshot();
        assert.equal(sessionView3.screen, "session");
        if (sessionView3.screen === "session") {
            assert.equal(sessionView3.notice, undefined);
        }

        // 验证旧 adapter 在切换后未收到新的模型调用
        assert.equal(initialAdapter.calls.length, 1);
    } finally {
        await cleanup();
    }
});

test("敏感凭据（Canary Secret）隔离审计：持久化快照、轨迹、Trace 日志、ViewModel 树均无任何泄漏", async () => {
    const { workspace, cleanup } = await setupE2eWorkspace();
    try {
        const catalogModels = [
            createDescriptor("model-alpha", "Model Alpha"),
            createDescriptor("model-beta", "Model Beta"),
        ];
        const initialAdapter = new SensitiveFakeAdapter("model-alpha");

        const root = await createCompositionRoot({
            cwd: workspace,
            env: { LAZYGOAL_HOME: join(workspace, "lazygoal-home") },
            adapter: initialAdapter,
            modelCatalog: new FakeCatalog(catalogModels),
            adapterFactory: (sel) => new SensitiveFakeAdapter(sel.modelId),
            profile: {
                id: "default",
                systemPrompt: "System prompt",
                instructions: [],
                toolIds: [],
            },
            toolPolicy: createDefaultToolPolicy(),
        });

        const capturedStates: UiViewModel[] = [];
        root.controller.subscribe(() => {
            capturedStates.push(JSON.parse(JSON.stringify(root.controller.getSnapshot())));
        });

        // 创建并推进 Goal
        await root.controller.dispatch({
            kind: "create",
            intent: "Perform canary audit task",
        });

        // 切换模型
        await root.controller.dispatch({ kind: "openModelSelector" });
        await root.controller.dispatch({
            kind: "selectModel",
            model: catalogModels[1]!,
        });

        // 再次推进
        await root.controller.dispatch({
            kind: "submitMessage",
            content: "Step 2 message",
        });

        // 1. 扫描当前测试 Home 下的所有文件（包括 goals 快照、trajectories 轨迹、traces 诊断日志）
        const lazygoalDir = join(workspace, "lazygoal-home");
        const leakedFiles = await scanDirectoryForSecret(lazygoalDir, CANARY_SECRET);
        assert.deepEqual(
            leakedFiles,
            [],
            `敏感凭证 ${CANARY_SECRET} 泄漏到了以下文件中：${leakedFiles.join(", ")}`,
        );

        // 2. 检查内存中发射过的所有 ViewModel 状态树
        const viewModelsJson = JSON.stringify(capturedStates);
        assert.equal(
            viewModelsJson.includes(CANARY_SECRET),
            false,
            "敏感凭据泄漏到了 UiViewModel 状态中！",
        );

        // 3. 检查持久化快照反序列化对象的 modelSelection 仅包含安全公开元数据
        const savedGoalId = root.controller.getSnapshot().screen === "session"
            ? (root.controller.getSnapshot() as any).goal.id
            : "";
        const savedGoal = await root.store.restore(savedGoalId);
        assert.ok(savedGoal !== undefined);
        const sel = savedGoal.state.modelSelection;
        assert.ok(sel !== undefined);
        assert.equal((sel as any).apiKey, undefined);
        assert.equal((sel as any).secret, undefined);
        assert.equal((sel as any).authorization, undefined);
    } finally {
        await cleanup();
    }
});

